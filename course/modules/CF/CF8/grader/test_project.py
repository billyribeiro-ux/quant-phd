# ---------------------------------------------------------------- oracle, one day at a time


def _day_rate(weekly: list[int], day: int) -> Fraction:
    """Cents of one day's flow on day `day`: week w's flow spread over its seven days; week 1's rate before day 1."""
    if day < 1:
        return Fraction(weekly[0], 7)
    return Fraction(weekly[(day - 1) // 7], 7)


def oracle_weekly_flows(weekly: list[int], lag: int) -> list[Fraction]:
    """Exact cents per week of a flow that falls due on each day and is paid or collected `lag` days later."""
    per_day = {day: _day_rate(weekly, day - lag) for day in range(1, 7 * HORIZON + 1)}
    return [sum((per_day[day] for day in range(7 * w + 1, 7 * w + 8)), Fraction(0)) for w in range(HORIZON)]


def half_up(value: Fraction) -> int:
    return math.floor(value + Fraction(1, 2))


def oracle_path(case: dict[str, Any], capped: bool) -> list[dict[str, int]]:
    receipts = oracle_weekly_flows(case["weekly_sales_cents"], case["collection_lag_days"])
    paid = oracle_weekly_flows(case["weekly_purchases_cents"], case["payment_lag_days"])
    cash = case["opening_cash_cents"]
    drawn = case["opening_drawn_cents"]
    rows: list[dict[str, int]] = []
    for w in range(HORIZON):
        got = half_up(receipts[w])
        out = half_up(paid[w] + case["weekly_opex_cents"][w])
        before = cash + got - out
        need = max(0, case["minimum_cash_cents"] - before)
        available = case["revolver_commitment_cents"] - drawn
        draw = min(need, max(available, 0)) if capped else need
        repay = 0 if need > 0 else min(before - case["minimum_cash_cents"], drawn)
        cash = before + draw - repay
        drawn += draw - repay
        liquidity = cash + case["revolver_commitment_cents"] - drawn
        rows.append(
            {
                "receipts_cents": got,
                "disbursements_cents": out,
                "draw_cents": draw,
                "repay_cents": repay,
                "ending_cash_cents": cash,
                "drawn_balance_cents": drawn,
                "liquidity_cents": liquidity,
                "headroom_cents": liquidity - case["covenant_threshold_cents"],
            }
        )
    return rows


def oracle_cumulative(weekly: list[int], lag: int) -> Fraction:
    """Cents collected (or paid) by day 91, counting sales from day -300: the window cancels in differences."""
    return sum((_day_rate(weekly, sale_day) for sale_day in range(-300, 7 * HORIZON + 1 - lag)), Fraction(0))


