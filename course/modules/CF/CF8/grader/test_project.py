def test_forecast_matches_the_oracle_path_on_every_fixture() -> None:
    for case in CASES:
        if forecast(case) != oracle_path(case, capped=True):
            pytest.fail("revolver path: the week-by-week rules of the specification give a different path.")


def test_draw_never_exceeds_availability() -> None:
    for case in CASES:
        drawn = case["opening_drawn_cents"]
        for row in forecast(case):
            if row["draw_cents"] > case["revolver_commitment_cents"] - drawn:
                pytest.fail("availability: a draw cannot exceed the undrawn commitment at the start of the week.")
            drawn = row["drawn_balance_cents"]


def test_drawn_balance_stays_between_zero_and_the_commitment() -> None:
    for case in CASES:
        for row in forecast(case):
            if not 0 <= row["drawn_balance_cents"] <= case["revolver_commitment_cents"]:
                pytest.fail("bounds: the drawn balance is never negative and never above the commitment.")


def test_repayment_never_exceeds_the_drawn_balance() -> None:
    for case in CASES:
        drawn = case["opening_drawn_cents"]
        for row in forecast(case):
            if row["repay_cents"] > drawn:
                pytest.fail("repayment: the revolver is repaid up to its drawn balance, never past it.")
            drawn = row["drawn_balance_cents"]


def test_no_week_both_draws_and_repays() -> None:
    for case in CASES:
        for row in forecast(case):
            if row["draw_cents"] and row["repay_cents"]:
                pytest.fail("one action: a week either draws or repays, never both.")


def test_draw_only_happens_when_cash_before_the_draw_is_below_minimum() -> None:
    for case in CASES:
        for row in forecast(case):
            before = row["ending_cash_cents"] - row["draw_cents"] + row["repay_cents"]
            if row["draw_cents"] > 0 and before >= case["minimum_cash_cents"]:
                pytest.fail("draw rule: the revolver draws only to hold minimum cash.")


def test_a_draw_covers_the_whole_need_when_availability_allows() -> None:
    case = flat_case(opening_cash=100_000, minimum=500_000, commitment=5_000_000)
    first = forecast(case)[0]
    if first["draw_cents"] != 500_000 - 0 or first["ending_cash_cents"] != 500_000:
        pytest.fail("draw rule: with enough availability the draw is exactly the shortfall to minimum cash.")


def test_a_draw_stops_at_availability_when_the_commitment_binds() -> None:
    row = forecast(TIGHT)[0]
    if row["draw_cents"] != 500_000 or row["ending_cash_cents"] != 500_000:
        pytest.fail("draw rule: the first week needs 500,000 cents and the commitment covers it.")
    later = forecast(TIGHT)
    if later[-1]["drawn_balance_cents"] != TIGHT["revolver_commitment_cents"]:
        pytest.fail("cap: once availability is used up, the drawn balance stops at the commitment.")
    if later[-1]["ending_cash_cents"] >= TIGHT["minimum_cash_cents"]:
        pytest.fail("cap: a binding commitment leaves cash below minimum, and the shortfall is reported.")


def test_minimum_cash_is_held_in_every_week_the_cap_does_not_bind() -> None:
    for case in CASES:
        drawn = case["opening_drawn_cents"]
        for row in forecast(case):
            available = case["revolver_commitment_cents"] - drawn
            before = row["ending_cash_cents"] - row["draw_cents"] + row["repay_cents"]
            uncapped = before < case["minimum_cash_cents"] and available >= case["minimum_cash_cents"] - before
            if uncapped and row["ending_cash_cents"] != case["minimum_cash_cents"]:
                pytest.fail("minimum cash: an uncapped draw lands cash exactly on the minimum.")
            if before >= case["minimum_cash_cents"] and row["ending_cash_cents"] < case["minimum_cash_cents"]:
                pytest.fail("minimum cash: cash above the minimum is never pushed below it by a repayment.")
            drawn = row["drawn_balance_cents"]


def test_repayment_sweeps_cash_above_minimum_to_the_drawn_balance() -> None:
    case = flat_case(sales=1_500_000, purchases=0, opex=0, lag=0, payment_lag=0, opening_cash=700_000)
    case["opening_drawn_cents"] = 300_000
    row = forecast(case)[0]
    if row["repay_cents"] != 300_000 or row["drawn_balance_cents"] != 0:
        pytest.fail("repayment: cash above minimum repays the drawn balance, capped at that balance.")
    if row["ending_cash_cents"] != 700_000 + 1_500_000 - 300_000:
        pytest.fail("repayment: the cash left after repaying is the cash before the repayment less the repayment.")


def test_repayment_is_capped_at_cash_above_minimum() -> None:
    case = flat_case(sales=1_000_000, purchases=0, opex=0, lag=0, payment_lag=0, opening_cash=500_000)
    case["opening_drawn_cents"] = 1_500_000
    case["revolver_commitment_cents"] = 2_000_000
    row = forecast(case)[0]
    if row["repay_cents"] != 1_000_000 or row["ending_cash_cents"] != 500_000:
        pytest.fail("repayment: when cash above minimum is smaller than the drawn balance, only that cash is repaid.")


def test_shortfall_reported_when_the_commitment_binds() -> None:
    plan = revolver_plan(TIGHT)
    rows = forecast(TIGHT)
    worst = max(max(0, TIGHT["minimum_cash_cents"] - row["ending_cash_cents"]) for row in rows)
    if plan["shortfall_cents"] != worst or worst <= 0:
        pytest.fail("shortfall: a binding commitment is reported as the largest gap below minimum cash, not hidden.")


def test_no_shortfall_reported_when_the_commitment_is_large_enough() -> None:
    big = case_with(TIGHT, revolver_commitment_cents=10_000_000)
    if revolver_plan(big)["shortfall_cents"] != 0:
        pytest.fail("shortfall: when every week's need is met, the reported shortfall is zero.")


def test_peak_drawn_includes_the_opening_balance() -> None:
    case = flat_case(sales=1_000_000, purchases=0, opex=0, lag=0, payment_lag=0, opening_cash=900_000)
    case["opening_drawn_cents"] = 400_000
    plan = revolver_plan(case)
    if plan["peak_drawn_cents"] != 400_000:
        pytest.fail("peak drawn: the peak is the largest drawn balance over the opening and the 13 weeks.")


def test_peak_drawn_is_the_largest_weekly_drawn_balance() -> None:
    for case in CASES:
        rows = forecast(case)
        want = max([case["opening_drawn_cents"]] + [row["drawn_balance_cents"] for row in rows])
        if revolver_plan(case)["peak_drawn_cents"] != want:
            pytest.fail("peak drawn: take the maximum of the weekly drawn balances, opening balance included.")


def test_required_commitment_is_the_uncapped_peak_draw() -> None:
    need = case_with(TIGHT, revolver_commitment_cents=10_000_000)
    required = revolver_plan(TIGHT)["required_commitment_cents"]
    uncapped_rows = oracle_path(need, False)
    if required != max([need["opening_drawn_cents"]] + [r["drawn_balance_cents"] for r in uncapped_rows]):
        pytest.fail("required commitment: the smallest commitment that meets every week's need, from the free path.")


def test_commitment_at_the_required_size_removes_the_shortfall_and_one_less_does_not() -> None:
    required = revolver_plan(TIGHT)["required_commitment_cents"]
    if revolver_plan(case_with(TIGHT, revolver_commitment_cents=required))["shortfall_cents"] != 0:
        pytest.fail("required commitment: at the required size no week is short of minimum cash.")
    if revolver_plan(case_with(TIGHT, revolver_commitment_cents=required - 1))["shortfall_cents"] <= 0:
        pytest.fail("required commitment: one cent below the required size leaves a shortfall.")


def test_required_commitment_is_at_least_the_opening_balance() -> None:
    for case in CASES:
        if revolver_plan(case)["required_commitment_cents"] < case["opening_drawn_cents"]:
            pytest.fail("required commitment: it cannot be below the balance already drawn at the start.")


def test_zero_commitment_is_valid_and_reports_the_shortfall() -> None:
    case = case_with(flat_case(), revolver_commitment_cents=0)
    plan = revolver_plan(case)
    if plan["shortfall_cents"] <= 0 or plan["peak_drawn_cents"] != 0:
        pytest.fail("commitment: zero is a valid commitment; no draw is possible and the gap is reported.")


# ---------------------------------------------------------------- covenant


def test_headroom_is_liquidity_minus_the_threshold_every_week() -> None:
    for case in CASES:
        for row in forecast(case):
            liquidity = row["ending_cash_cents"] + case["revolver_commitment_cents"] - row["drawn_balance_cents"]
            headroom = liquidity - case["covenant_threshold_cents"]
            if row["liquidity_cents"] != liquidity or row["headroom_cents"] != headroom:
                pytest.fail(
                    "covenant: liquidity is cash plus undrawn availability at week end; headroom is the excess."
                )


def test_pinch_week_is_the_week_with_the_smallest_headroom() -> None:
    for case in CASES:
        rows = forecast(case)
        smallest = min(row["headroom_cents"] for row in rows)
        pinch = covenant_pinch(case)
        if pinch["headroom_cents"] != smallest or rows[pinch["week"] - 1]["headroom_cents"] != smallest:
            pytest.fail("pinch: the pinch week is the week of smallest headroom, read from weeks 1 to 13.")


def test_pinch_week_breaks_a_tie_toward_the_earliest_week() -> None:
    if covenant_pinch(TIE) != {"week": 1, "headroom_cents": forecast(TIE)[0]["headroom_cents"]}:
        pytest.fail("pinch tie: when headroom is equal in several weeks, the earliest week is the pinch.")


def test_pinch_on_the_instance_is_the_earliest_argmin() -> None:
    rows = forecast(CASE)
    best = min(range(HORIZON), key=lambda i: (rows[i]["headroom_cents"], i))
    if covenant_pinch(CASE) != {"week": best + 1, "headroom_cents": rows[best]["headroom_cents"]}:
        pytest.fail("pinch: the week and headroom must match the earliest smallest headroom of this case.")


# ---------------------------------------------------------------- working-capital actions


def test_zero_days_changes_nothing() -> None:
    if action_cash_impact(CASE, "dso", 0) != 0 or action_cash_impact(CASE, "dpo", 0) != 0:
        pytest.fail("action: a change of zero days has zero cash impact.")


def test_dso_shortening_matches_the_day_oracle() -> None:
    lag = CASE["collection_lag_days"]
    for days in (1, 5, lag):
        base = oracle_cumulative(CASE["weekly_sales_cents"], lag)
        new = oracle_cumulative(CASE["weekly_sales_cents"], lag - days)
        if action_cash_impact(CASE, "dso", days) != half_up(new - base):
            pytest.fail("DSO: shortening collections by d days moves the sales of the d days now collected earlier.")


def test_dpo_lengthening_matches_the_day_oracle() -> None:
    lag = CASE["payment_lag_days"]
    for days in (1, 5, 20):
        base = oracle_cumulative(CASE["weekly_purchases_cents"], lag)
        new = oracle_cumulative(CASE["weekly_purchases_cents"], lag + days)
        if action_cash_impact(CASE, "dpo", days) != half_up(base - new):
            pytest.fail("DPO: lengthening payables by d days keeps the purchases of the d days now paid later.")


def test_dso_shortening_has_the_closed_form_for_steady_sales() -> None:
    case = flat_case(sales=1_000_000, lag=40)
    if action_cash_impact(case, "dso", 5) != half_up(Fraction(5 * 1_000_000, 7)):
        pytest.fail("DSO: with steady sales, shortening by d days releases d days of sales, d times the daily rate.")


def test_dpo_lengthening_has_the_closed_form_for_steady_purchases() -> None:
    case = flat_case(purchases=700_000, payment_lag=30, sales=0, opex=0)
    if action_cash_impact(case, "dpo", 4) != half_up(Fraction(4 * 700_000, 7)):
        pytest.fail("DPO: with steady purchases, lengthening by d days keeps d days of purchases at the daily rate.")


def test_shortening_collections_raises_cash_and_lengthening_payables_raises_cash() -> None:
    if action_cash_impact(CASE, "dso", 3) <= 0:
        pytest.fail("DSO sign: shortening collections raises cash; the impact is positive when sales are positive.")
    if action_cash_impact(CASE, "dpo", 3) <= 0:
        pytest.fail("DPO sign: lengthening payables keeps cash in the business; the impact is positive.")


def test_an_action_on_zero_flows_has_zero_impact() -> None:
    case = flat_case(sales=0, purchases=0, opex=0)
    if action_cash_impact(case, "dso", 4) != 0 or action_cash_impact(case, "dpo", 4) != 0:
        pytest.fail("action: with no sales or purchases there is no cash to move.")


def test_dso_change_equal_to_the_whole_lag_is_accepted() -> None:
    lag = CASE["collection_lag_days"]
    value = action_cash_impact(CASE, "dso", lag)
    if not isinstance(value, int):
        pytest.fail("action: shortening by the whole current lag is a valid change with an integer result.")


