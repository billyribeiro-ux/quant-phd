def test_instance_inputs_are_valid_cases() -> None:
    if CASE["minimum_cash_cents"] <= 0:
        pytest.fail("instance: minimum cash is positive by construction.")
    if CASE["revolver_commitment_cents"] < CASE["opening_drawn_cents"]:
        pytest.fail("instance: the commitment is at least the opening drawn balance.")
    if not 20 <= CASE["collection_lag_days"] <= 90:
        pytest.fail("instance: the collection lag is between 20 and 90 days.")
    for key in ("weekly_sales_cents", "weekly_purchases_cents", "weekly_opex_cents"):
        if len(CASE[key]) != HORIZON or any(not isinstance(v, int) or v < 0 for v in CASE[key]):
            pytest.fail("instance: each weekly list has 13 non-negative whole-cent values.")


def test_the_seed_case_matches_the_oracle_on_every_output() -> None:
    rows = forecast(CASE)
    if rows != oracle_path(CASE, capped=True):
        pytest.fail("seed case: the forecast on this seed's case differs from the oracle path.")
    plan = revolver_plan(CASE)
    path = oracle_path(CASE, capped=True)
    peak = max([CASE["opening_drawn_cents"]] + [r["drawn_balance_cents"] for r in path])
    if plan["peak_drawn_cents"] != peak:
        pytest.fail("seed case: the peak drawn balance differs from the oracle.")
    pinch = covenant_pinch(CASE)
    best = min(range(HORIZON), key=lambda i: (path[i]["headroom_cents"], i))
    if pinch != {"week": best + 1, "headroom_cents": path[best]["headroom_cents"]}:
        pytest.fail("seed case: the pinch differs from the oracle's earliest smallest headroom.")


