# ---------------------------------------------------------------- receipts and disbursements


def test_receipts_match_the_day_by_day_oracle() -> None:
    for case in CASES:
        want = [half_up(x) for x in oracle_weekly_flows(case["weekly_sales_cents"], case["collection_lag_days"])]
        got = [row["receipts_cents"] for row in forecast(case)]
        if got != want:
            pytest.fail("receipts: a collection lag moves each day's sales into a later day; check the day shift.")


def test_disbursements_match_the_day_by_day_oracle() -> None:
    for case in CASES:
        paid = oracle_weekly_flows(case["weekly_purchases_cents"], case["payment_lag_days"])
        want = [half_up(paid[w] + case["weekly_opex_cents"][w]) for w in range(HORIZON)]
        got = [row["disbursements_cents"] for row in forecast(case)]
        if got != want:
            pytest.fail("disbursements: purchases are paid after the payment lag, and opex is paid in its week.")


def test_zero_lags_collect_and_pay_each_weeks_flow_in_that_week() -> None:
    case = flat_case(sales=700_000, purchases=400_000, opex=100_000, lag=0, payment_lag=0)
    rows = forecast(case)
    if any(row["receipts_cents"] != 700_000 for row in rows):
        pytest.fail("zero collection lag: each week's sales are collected in that week.")
    if any(row["disbursements_cents"] != 500_000 for row in rows):
        pytest.fail("zero payment lag: purchases are paid in their week, together with opex.")


def test_a_four_sevenths_cent_rounds_up_and_a_two_sevenths_cent_rounds_down() -> None:
    four = flat_case(sales=0, lag=1)
    four["weekly_sales_cents"] = [4, 0] + [0] * (HORIZON - 2)
    two = copy.deepcopy(four)
    two["weekly_sales_cents"] = [2, 0] + [0] * (HORIZON - 2)
    if forecast(four)[1]["receipts_cents"] != 1:
        pytest.fail("rounding: 4/7 of a cent is above one half, so it rounds up to 1 once, half up.")
    if forecast(two)[1]["receipts_cents"] != 0:
        pytest.fail("rounding: 2/7 of a cent is below one half, so it rounds down to 0.")


def test_cash_identity_holds_in_every_week() -> None:
    for case in CASES:
        previous = case["opening_cash_cents"]
        for row in forecast(case):
            flows = row["receipts_cents"] - row["disbursements_cents"] + row["draw_cents"] - row["repay_cents"]
            if row["ending_cash_cents"] != previous + flows:
                pytest.fail("identity: ending cash = opening cash + receipts - disbursements + draw - repayment.")
            previous = row["ending_cash_cents"]


def test_liquidity_moves_only_with_net_operating_flows() -> None:
    for case in CASES:
        rows = forecast(case)
        previous = case["opening_cash_cents"] + case["revolver_commitment_cents"] - case["opening_drawn_cents"]
        for row in rows:
            previous += row["receipts_cents"] - row["disbursements_cents"]
            if row["liquidity_cents"] != previous:
                pytest.fail("liquidity: a draw moves cash and undrawn line by equal amounts, so only flows move it.")


