def must_raise(call: Callable[[], object], condition: str) -> None:
    """Fail with the violated condition unless call() raises ValueError."""
    __tracebackhide__ = True
    try:
        call()
    except ValueError:
        return
    pytest.fail(f"{condition}: the specification requires a ValueError for this input.")


def case_with(case: dict[str, Any], **changes: Any) -> dict[str, Any]:
    out = copy.deepcopy(case)
    out.update(changes)
    return out


