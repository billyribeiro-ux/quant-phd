def test_evaluate_model_scorecard() -> None:
    """Verify that evaluate_model_scorecard accurately measures distance from empirical targets."""
    inst = _get_instance()
    targets = inst["targets"]
    weights = inst["weights"]

    # Perfect match test
    score_perfect = evaluate_model_scorecard(targets, targets, weights)
    assert np.isclose(score_perfect["weighted_loss"], 0.0, atol=1e-10), "Perfect match must have zero weighted loss"
    assert score_perfect["moments_matched"] == len(targets), "All moments should be matched on perfect data"

    # Perturbed test
    perturbed = np.asarray(targets) * 1.20
    score_perturbed = evaluate_model_scorecard(perturbed, targets, weights)
    assert score_perturbed["weighted_loss"] > 0.0, "Perturbed moments must yield positive loss"
    assert np.isclose(score_perturbed["mean_absolute_percentage_error"], 0.20, atol=1e-2)


def test_run_horse_race() -> None:
    """Test that run_horse_race successfully simulates and ranks all three canonical models."""
    inst = _get_instance()

    race_result = run_horse_race(inst)

    assert "scorecards" in race_result
    assert "winner" in race_result
    assert "models_scores" in race_result

    scorecards = race_result["scorecards"]
    for m in ("campbell_cochrane", "bansal_yaron", "barro_rietz"):
        assert m in scorecards, f"Scorecard missing model {m}"
        assert "sim_moments" in scorecards[m]
        assert "weighted_loss" in scorecards[m]
        assert len(scorecards[m]["sim_moments"]) == 12, "Each model must evaluate all 12 moments"

    winner = race_result["winner"]
    scores = race_result["models_scores"]
    assert winner in scores, f"Winner {winner} not in model scores"
    min_score = min(scores.values())
    assert np.isclose(scores[winner], min_score, atol=1e-6), "Winner must have the minimal weighted loss"
