"""Autograder test suite for AP4 Model Horse Race project.

Validates the simulation, moment extraction, and comparative scorecard evaluation
for Campbell-Cochrane (1999), Bansal-Yaron (2004), and Barro-Rietz (1988, 2006).
"""

from __future__ import annotations

import os
from typing import Any

import numpy as np
from instance import BY_PARAM_NAMES, make_instance
from model_horse_race import (
    _to_dict,
    compute_twelve_moments,
    evaluate_model_scorecard,
    run_horse_race,
    simulate_bansal_yaron,
    simulate_barro_rietz,
    simulate_campbell_cochrane,
)


def _get_instance() -> dict[str, Any]:
    seed = int(os.environ.get("QF_SEED", "0"))
    return make_instance(seed)


EXPECTED_MOMENTS = [
    "mean_consumption_growth",
    "vol_consumption_growth",
    "ac1_consumption_growth",
    "mean_equity_premium",
    "vol_equity_return",
    "sharpe_ratio",
    "mean_risk_free_rate",
    "vol_risk_free_rate",
    "mean_log_pd",
    "vol_log_pd",
    "ac1_log_pd",
    "predictability_slope_1y",
]


def test_twelve_moments_extraction() -> None:
    """Check that compute_twelve_moments produces all 12 canonical moments with correct mathematical relationships."""
    rng = np.random.default_rng(12345)
    t = 200
    mock_data = {
        "consumption_growth": rng.normal(0.02, 0.03, t),
        "excess_return": rng.normal(0.06, 0.18, t),
        "risk_free_rate": np.full(t, 0.01),
        "log_pd": 3.4 + rng.normal(0, 0.3, t),
    }

    moments = compute_twelve_moments(mock_data)

    # 1. Check all keys present
    for k in EXPECTED_MOMENTS:
        assert k in moments, f"Missing moment: {k}"
        assert np.isfinite(moments[k]), f"Moment {k} is not finite: {moments[k]}"

    # 2. Check Sharpe ratio formula
    expected_sr = moments["mean_equity_premium"] / moments["vol_equity_return"]
    assert np.isclose(moments["sharpe_ratio"], expected_sr, atol=1e-6), "Sharpe ratio must equal mean / vol"

    # 3. Check autocorrelations are within [-1, 1]
    assert -1.0 <= moments["ac1_consumption_growth"] <= 1.0, "AC1 of consumption growth must be in [-1, 1]"
    assert -1.0 <= moments["ac1_log_pd"] <= 1.0, "AC1 of log(P/D) must be in [-1, 1]"


def test_campbell_cochrane_invariants() -> None:
    """Test Campbell-Cochrane model: constant risk-free rate and habit-induced return volatility."""
    inst = _get_instance()
    t_len = int(inst["t_len"])
    seed = int(inst["seed"])
    cc_params = inst["cc_params"]

    res = simulate_campbell_cochrane(cc_params, t_len, seed)

    # Required output keys
    for k in ("consumption_growth", "excess_return", "risk_free_rate", "log_pd"):
        assert k in res, f"simulate_campbell_cochrane missing key {k}"
        assert len(res[k]) == t_len - 1, f"Expected length {t_len - 1}, got {len(res[k])}"
        assert np.all(np.isfinite(res[k])), f"Non-finite values found in {k}"

    rf = res["risk_free_rate"]
    # The hallmark of Campbell-Cochrane's sensitivity function lambda(s) is an analytically constant risk-free rate
    rf_std = float(np.std(rf))
    assert rf_std < 1e-6, f"Campbell-Cochrane risk-free rate must be constant, but has std {rf_std}"

    # Excess returns must show substantial volatility generated by habit variation
    re_std = float(np.std(res["excess_return"]))
    assert re_std > 0.05, f"Campbell-Cochrane excess return volatility must exceed 0.05, got {re_std}"


def test_bansal_yaron_long_run_risk() -> None:
    """Test Bansal-Yaron model: early resolution of uncertainty and time-varying risk-free rate."""
    inst = _get_instance()
    t_len = int(inst["t_len"])
    seed = int(inst["seed"])
    by_params = _to_dict(inst["by_params"], BY_PARAM_NAMES)

    res = simulate_bansal_yaron(by_params, t_len, seed)

    for k in ("consumption_growth", "excess_return", "risk_free_rate", "log_pd"):
        assert k in res, f"simulate_bansal_yaron missing key {k}"
        assert len(res[k]) == t_len - 1, f"Expected length {t_len - 1}, got {len(res[k])}"
        assert np.all(np.isfinite(res[k])), f"Non-finite values found in {k}"

    # In Bansal-Yaron, the real risk-free rate varies over time with expected growth and economic uncertainty
    rf_std = float(np.std(res["risk_free_rate"]))
    assert rf_std > 1e-5, f"Bansal-Yaron risk-free rate must be time-varying, got std {rf_std}"

    # Valuation sensitivity A1_m must be strictly positive under psi > 1
    psi = by_params["psi"]
    phi_d = by_params["phi_d"]
    assert psi > 1.0, "Bansal-Yaron calibration requires EIS psi > 1"
    assert phi_d > 1.0 / psi, "Dividend leverage phi_d must exceed 1/psi"


