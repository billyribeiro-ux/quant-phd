"""Round 20 recomputation of L05 prose numbers (Decimal, 60 digits). Run with python -I."""
from decimal import Decimal as D, getcontext
getcontext().prec = 60
r = D("0.05")
delta = (1+r).ln()
print("delta", f"{delta:.12f}")
for t in (D("0.5"), D(1), D(2), D(5), D(10)):
    a = (1+r)**(-t); s = (1+r/2)**(-2*t); c = (-r*t).exp(); q = (-delta*t).exp()
    print("t", t, "annual", f"{a:.12f}", "semi", f"{s:.12f}", "cont", f"{c:.12f}", "equiv", f"{q:.12f}", "maxgap", f"{abs(q-a):.2e}")
P = D(1000000)
a5=(1+r)**-5; s5=(1+r/2)**-10; c5=(-r*5).exp()
print("PV5 annual", f"{P*a5:.4f}", "semi", f"{P*s5:.4f}", "cont", f"{P*c5:.4f}")
print("annual-semi unrounded", f"{P*a5-P*s5:.4f}", "semi-cont unrounded", f"{P*s5-P*c5:.4f}", "annual-cont unrounded", f"{P*a5-P*c5:.4f}")
print("annual-semi printed", 783526-781198, "semi-cont printed", 781198-778801, "annual-cont printed", 783526-778801)
print("E3 annual 10y", f"{P*(1+r)**-10:.4f}")
print("M1 1.04^-3", f"{(D('1.04')**-3):.12f}", "1/1.124864", f"{1/D('1.124864'):.12f}")
print("M2 1/1.1236", f"{1/D('1.1236'):.12f}", "250000x0.88999644", f"{250000*D('0.88999644'):.4f}", "exact 250000/1.1236", f"{250000/D('1.1236'):.4f}")
print("M3 e^-0.06", f"{(D('-0.06')).exp():.12f}", "500000x", f"{500000*(D('-0.06')).exp():.4f}")
print("1.05^-5", f"{(D('1.05')**-5):.12f}")
print("1/1.1025", f"{1/D('1.1025'):.12f}")
print("e^-0.5", f"{(D('-0.5')).exp():.12f}")
print("ln1.05", f"{D('1.05').ln():.12f}")
print("1 - e^-0.05 check", f"{D('0.05').exp()-1:.12f}")
# R2
x = 1/D('0.6')
rr = x**(D(1)/10)  # (1/0.6)^(1/10)
print("R2 root", f"{rr:.14f}", "r", f"{rr-1:.12f}")
print("R2 check (1+r)^10", f"{(D('1.052409779149'))**10:.12f}", "1/that", f"{1/((D('1.052409779149'))**10):.12f}")
print("R2 shorter 1.0524097791 ^10", f"{(D('1.0524097791'))**10:.12f}")
print("R2 error 1+r", f"{D('1.052409779149')-D('1.0524097791'):.3e}", "10(1+r)^9", f"{10*(D('1.052409779149'))**9:.6f}")
print("R2 magnified", f"{((D('1.052409779149'))**10 - (D('1.0524097791'))**10):.3e}")
print("R3 e^0.05 - 1", f"{(D('0.05')).exp()-1:.12f}", "1.05^-5 vs e^-0.25", f"{((D('1.0512710964'))**-5):.12f}", f"{(D('-0.25')).exp():.12f}")
print("P3/misc: 1.05^-1 vs e^-0.05 check", f"{(1+r)**-1:.12f}", f"{(-r).exp():.12f}")
print("E2 unrounded annual-semi", f"{((1+r)**(-D('0.5')) - (1+r/2)**(-1)):.14f}")
print("MISC 1/1.6666", f"{1/D('1.6666666667'):.10f}")
