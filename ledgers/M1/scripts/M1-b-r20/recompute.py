"""Round 20 recomputation of every L04/L05 prose number (Decimal, 60 digits). Run with python -I."""
from decimal import Decimal as D, getcontext, ROUND_HALF_EVEN
getcontext().prec = 60
r = D("0.05")
def F(m, years=1): return (1 + r/m) ** (m*years)
e_r = (r).exp()
print("e^0.05 =", f"{e_r:.12f}")
for m in (1,2,4,12,365,1000,10000,100000,1000000):
    print("m", m, "F", f"{F(m):.12f}", "err", f"{e_r-F(m):.13f}")
e1000 = e_r - F(1000); e10000 = e_r - F(10000); e100000 = e_r - F(100000)
print("ratio 1000->10000 unrounded", f"{e1000/e10000:.5f}", "printed", f"{D('0.0000013140')/D('0.0000001314'):.5f}")
print("ratio 10000->100000 unrounded", f"{e10000/e100000:.5f}", "printed", f"{D('0.0000001314')/D('0.0000000131'):.5f}")
P = D(1000000)
ann = P*F(1)*0 + P*F(1,10)
mon = P*F(12,10); dai = P*F(365,10); con = P*(r*10).exp()
print("PV10 annual", f"{ann:.4f}", "monthly", f"{mon:.4f}", "daily", f"{dai:.4f}", "cont", f"{con:.4f}")
print("monthly-annual unrounded", f"{mon-ann:.4f}", "cont-daily unrounded", f"{con-dai:.4f}")
print("monthly-daily unrounded", f"{dai-mon:.4f}", "ratio", f"{(dai-mon)/(con-dai):.4f}", "printed-ratio", f"{D(1656)/D(56):.4f}")
print("E3 printed ratio check 1656/56 =", f"{D(1656)/D(56):.6f}")
print("EAR 365 - EAR 12", f"{F(365)-F(12):.12f}")
print("E1 difference decimals", f"{D('0.0512674965')-D('0.0511618979'):.10f}")
print("8pct monthly EAR", f"{(1+D('0.08')/12)**12-1:.12f}", "periodic", f"{(1+D('0.08')/12)**12:.12f}")
print("M2 e^0.18", f"{(D('0.18')).exp():.12f}", "1000x", f"{1000*(D('0.18')).exp():.6f}", "cents", f"{100000*(D('0.18')).exp():.6f}")
e005_12 = (D('0.05')/12).exp()
print("e^(0.05/12)", f"{e005_12:.14f}", "12x-1", f"{12*(e005_12-1):.14f}")
r12 = 12*(e005_12-1)
