"""Round 13 check: every number token in cards.json must appear in its own lesson text
(stripped HTML, regenerated by strip_lessons_r13.py) or in the printed lab stdout; also
duplicate and id/lesson/grade structure. Usage: python3 -I cards_numbers_r13.py <cards.json> <scratch_dir>"""
import json, re, sys, os
cards_path, scratch = sys.argv[1], sys.argv[2]
cards = json.load(open(cards_path, encoding="utf-8"))
texts = {}
for lesson in ("L01", "L02", "L03", "L04"):
    texts[lesson] = open(os.path.join(scratch, lesson + ".txt"), encoding="utf-8").read()
labs = {}
for lesson, lab in (("L01", "lab-LX2-L01-1"), ("L02", "lab-LX2-L02-1"), ("L03", "lab-LX2-L03-1"), ("L04", "lab-LX2-L04-1")):
    labs[lesson] = open(os.path.join(scratch, "run", lab + ".stdout"), encoding="utf-8").read()
NUM = re.compile(r"(?<![A-Za-z(])\d+(?:[.,]\d+)*")
# tokens that are structural (section/proposition/theorem labels, ids) rather than claims
STRUCT_PREFIX = re.compile(r"(Definition|Proposition|Theorem|Problem|Lab|Assumption|Part|Standard|section|sections|Section|Remark|Research|Lesson|Lab 1|E|P|R|pp?\.|n\.)\s*$")
problems = []
seen = {}
for c in cards:
    cid = c["id"]
    if c["lesson"] not in texts:
        problems.append((cid, "bad lesson"))
    for field in ("front", "back"):
        key = c[field].strip().lower()
        if key in seen and seen[key] != cid:
            problems.append((cid, "duplicate " + field + " with " + seen[key]))
        seen.setdefault(key, cid)
    text = c["front"] + " " + c["back"]
    corpus = texts[c["lesson"]] + " " + labs[c["lesson"]] + " " + " ".join(texts.values())
    for m in NUM.finditer(text):
        tok = m.group(0)
        if tok in corpus:
            continue
        problems.append((cid, "number not in lesson/lab text: " + tok))
print("cards:", len(cards), "ids:", cards[0]["id"], "..", cards[-1]["id"])
ids = [c["id"] for c in cards]
print("duplicate ids:", len(ids) - len(set(ids)))
print("grade counts:", {g: sum(1 for c in cards if c.get("grade") == g) for g in ("T", "C", None)})
for p in problems:
    print("PROBLEM", p)
print("problems:", len(problems))
