"""M6 L07 lab 1: conditional expectation on a finite space as the L2 projection onto partition-measurable functions.

Inputs are a fixed finite probability space with eight outcomes, not data, and no random draws are used.
The sigma-algebra G is generated by the partition {0,1,2}, {3,4}, {5,6,7} of the outcomes.

Part A: the cell-average formula E[X | G] = E[X 1_B] / P(B) on each cell B.
Part B: the L2 projection of X onto the span of three functions that span the G-measurable functions, found by
solving the normal equations exactly; it is compared with Part A, and the residual is checked to be orthogonal to
each spanning function.
Part C: the mean squared error E[(X - Y)^2] of the cell averages and of all 125 cell-constant functions whose cell
values lie in {-2, -1, 0, 1, 2}. No function among these 125 has a smaller error than the cell average.
Part D: the tower property for the coarser sigma-algebra H generated by {0,1,2,3,4}, {5,6,7}, and the identity
E[E[X | G]] = E[X].

Every probability, value and projection is a Fraction, so every equality test is exact.
"""

from fractions import Fraction
from itertools import product

P = tuple(Fraction(n, 16) for n in (1, 2, 1, 3, 2, 3, 2, 2))
X = tuple(Fraction(v) for v in (2, -1, 4, 0, 3, -2, 1, 5))
CELLS = ((0, 1, 2), (3, 4), (5, 6, 7))
COARSE = ((0, 1, 2, 3, 4), (5, 6, 7))


def expect(values: tuple[Fraction, ...], event: tuple[int, ...]) -> Fraction:
    """The expectation of `values` times the indicator of `event`, a set of outcome indices."""
    return sum((P[w] * values[w] for w in event), Fraction(0))


def prob(event: tuple[int, ...]) -> Fraction:
    """The probability of an event, a set of outcome indices."""
    return sum((P[w] for w in event), Fraction(0))


def cell_average(cells: tuple[tuple[int, ...], ...]) -> tuple[Fraction, ...]:
    """The function that equals E[X 1_B] / P(B) on each cell B and is constant on cells."""
    out = [Fraction(0)] * len(P)
    for cell in cells:
        value = expect(X, cell) / prob(cell)
        for w in cell:
            out[w] = value
    return tuple(out)


def solve(matrix: list[list[Fraction]], rhs: list[Fraction]) -> list[Fraction]:
    """Solve a small square linear system by Gaussian elimination in exact arithmetic."""
    n = len(rhs)
    rows = [[*row, rhs[i]] for i, row in enumerate(matrix)]
    for col in range(n):
        pivot = next(r for r in range(col, n) if rows[r][col] != 0)
        rows[col], rows[pivot] = rows[pivot], rows[col]
        for r in range(n):
            if r != col and rows[r][col] != 0:
                factor = rows[r][col] / rows[col][col]
                rows[r] = [a - factor * b for a, b in zip(rows[r], rows[col], strict=True)]
    return [rows[i][n] / rows[i][i] for i in range(n)]


def mse(y: tuple[Fraction, ...]) -> Fraction:
    """The mean squared error E[(X - Y)^2] of a function Y."""
    return sum((P[w] * (X[w] - y[w]) ** 2 for w in range(len(P))), Fraction(0))


def part_a() -> tuple[Fraction, ...]:
    """Print the cell averages and return them."""
    average = cell_average(CELLS)
    print("Part A: cell averages E[X | G] = E[X 1_B] / P(B)")
    for cell in CELLS:
        print(f"cell {cell} prob {prob(cell)} average {expect(X, cell) / prob(cell)}")
    return average


def part_b(average: tuple[Fraction, ...]) -> None:
    """Solve the normal equations for the projection onto span{1, 1_{B1}, 1_{B1 u B2}} and compare."""
    basis = [
        tuple(Fraction(1) for _ in P),
        tuple(Fraction(1) if w in CELLS[0] else Fraction(0) for w in range(len(P))),
        tuple(Fraction(1) if w in CELLS[0] + CELLS[1] else Fraction(0) for w in range(len(P))),
    ]
    gram = [
        [expect(tuple(a * b for a, b in zip(u, v, strict=True)), tuple(range(len(P)))) for v in basis] for u in basis
    ]
    rhs = [expect(tuple(a * x for a, x in zip(u, X, strict=True)), tuple(range(len(P)))) for u in basis]
    coef = solve(gram, rhs)
    projection = tuple(sum((c * u[w] for c, u in zip(coef, basis, strict=True)), Fraction(0)) for w in range(len(P)))
    print("Part B: L2 projection by normal equations")
    print("coefficients " + " ".join(str(c) for c in coef))
    print(f"projection_equals_cell_average {projection == average}")
    residual = tuple(x - y for x, y in zip(X, projection, strict=True))
    orthogonal = [expect(tuple(r * b for r, b in zip(residual, u, strict=True)), tuple(range(len(P)))) for u in basis]
    print("residual_inner_products " + " ".join(str(v) for v in orthogonal))
    print(f"residual_orthogonal {all(v == 0 for v in orthogonal)}")


def part_c(average: tuple[Fraction, ...]) -> None:
    """Enumerate the 125 cell-constant functions with values in {-2,...,2} and compare their errors."""
    values = (-2, -1, 0, 1, 2)
    errors = []
    for triple in product(values, repeat=len(CELLS)):
        y = [Fraction(0)] * len(P)
        for cell, v in zip(CELLS, triple, strict=True):
            for w in cell:
                y[w] = Fraction(v)
        errors.append(mse(tuple(y)))
    best = mse(average)
    print("Part C: mean squared error over cell-constant functions")
    print(f"candidates_checked {len(errors)}")
    print(f"average_mse {best} = {float(best):.10f}")
    print(f"average_mse_is_minimum {all(best <= e for e in errors)}")
    print(f"candidates_with_equal_mse {sum(1 for e in errors if e == best)}")


def part_d(average: tuple[Fraction, ...]) -> None:
    """Check E[E[X|G] | H] = E[X|H] on each H-cell, and E[E[X|G]] = E[X]."""
    print("Part D: tower property and the total expectation")
    for cell in COARSE:
        lhs = expect(average, cell) / prob(cell)
        rhs = expect(X, cell) / prob(cell)
        print(f"coarse_cell {cell} lhs {lhs} rhs {rhs} equal {lhs == rhs}")
    everything = tuple(range(len(P)))
    print(f"total_expectation_equal {expect(average, everything) == expect(X, everything)}")


def main() -> None:
    """Print Parts A to D."""
    average = part_a()
    part_b(average)
    part_c(average)
    part_d(average)


main()
