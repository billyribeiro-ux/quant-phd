"""M6 L08 lab 1: the martingale property of a +1/-1 walk on its natural filtration, checked on all 2^10 paths.

Inputs are a fixed finite probability space, not data. The walk is S_0 = 0, S_k = X_1 + ... + X_k, where each step
X_i is +1 with probability p and -1 with probability 1 - p, independently. Two walks are tested on the same tree:
the fair walk with p = 1/2 and a biased walk with p = 1/3. No random draws are used.

The filtration F_k is generated by the first k steps. Its cells at level k are the sets of paths that share a
prefix of length k, so there are 2^k cells at level k. For each cell A at level k the lab computes the cell average
of S_{k+1}, E[S_{k+1} 1_A] / P(A), and compares it with S_k on the same cell. A walk is a martingale on this tree
when the two agree on every cell at every level k = 0, ..., 9.

Every probability and value is a Fraction, so every comparison is exact.
"""

from fractions import Fraction
from itertools import product

N = 10
FAIR = Fraction(1, 2)
BIASED = Fraction(1, 3)


def path_probability(path: tuple[int, ...], p: Fraction) -> Fraction:
    """The probability of a path of +1/-1 steps when each step is +1 with probability p, independently."""
    out = Fraction(1)
    for step in path:
        out *= p if step == 1 else 1 - p
    return out


def partial_sum(path: tuple[int, ...], k: int) -> int:
    """S_k along a path: the sum of its first k steps, with S_0 = 0."""
    return sum(path[:k])


def level_check(paths: list[tuple[int, ...]], p: Fraction, k: int) -> tuple[int, int, Fraction]:
    """At level k, count the cells and the paths where the cell average of S_{k+1} differs from S_k.

    Returns (cells that agree on every path in them, paths whose cell average differs from S_k, the common
    increment E[S_{k+1} - S_k | A] of the first cell). The increment is printed only as a check of the formula 2p - 1.
    """
    cells: dict[tuple[int, ...], list[tuple[int, ...]]] = {}
    for path in paths:
        cells.setdefault(path[:k], []).append(path)
    agreeing = 0
    mismatched = 0
    first_increment = Fraction(0)
    for index, (prefix, members) in enumerate(cells.items()):
        mass = sum((path_probability(q, p) for q in members), Fraction(0))
        cell_average = sum((path_probability(q, p) * partial_sum(q, k + 1) for q in members), Fraction(0)) / mass
        level_value = partial_sum(prefix, k)
        differing = sum(1 for q in members if cell_average != level_value)
        mismatched += differing
        if differing == 0:
            agreeing += 1
        if index == 0:
            first_increment = cell_average - level_value
    return agreeing, mismatched, first_increment


def nested(paths: list[tuple[int, ...]]) -> bool:
    """Each cell at level k is the union of exactly two cells at level k + 1, so the filtration increases."""
    for k in range(N):
        coarse = {path[:k] for path in paths}
        fine = {path[: k + 1] for path in paths}
        for prefix in coarse:
            children = {(*prefix, 1), (*prefix, -1)}
            if not children <= fine:
                return False
    return True


def main() -> None:
    """Print the filtration check, then the level-by-level martingale check for the fair and the biased walk."""
    paths = list(product((1, -1), repeat=N))
    print(f"paths {len(paths)} steps {N}")
    print(f"filtration_nested {nested(paths)}")
    total_mass = sum((path_probability(q, FAIR) for q in paths), Fraction(0))
    print(f"total_mass_fair {total_mass}")

    for label, p in (("fair", FAIR), ("biased", BIASED)):
        print(f"Walk {label} with p = {p}")
        cells_agreeing = 0
        cells_total = 0
        mismatched_total = 0
        for k in range(N):
            agreeing, mismatched, increment = level_check(paths, p, k)
            cells_total += 2**k
            cells_agreeing += agreeing
            mismatched_total += mismatched
            print(f"level {k} cells {2**k} agreeing {agreeing} mismatched_paths {mismatched} increment {increment}")
        print(f"cells_agreeing {cells_agreeing} of {cells_total}")
        print(f"mismatched_paths_all_levels {mismatched_total}")
        expected_mean = sum((path_probability(q, p) * partial_sum(q, N) for q in paths), Fraction(0))
        print(f"expected_S_N {expected_mean} equals 2p-1 times N: {expected_mean == N * (2 * p - 1)}")


main()
