"""Lab 1 for PM2 L04: Power-Law Portfolio Outcomes vs. Fund Size.

SIMULATED: Monte Carlo evaluation of venture capital portfolio construction under power-law returns.
Models deal return multiples R_i using a realistic two-component mixture:
- 60% probability of failure/loss: Uniform(0.0, 0.8)
- 30% probability of modest success: Uniform(1.0, 5.0)
- 10% probability of power-law home run: Pareto distribution with scale x_m = 5.0 and tail exponent alpha = 1.4.

Evaluates 5,000 simulated funds across portfolio sizes N in {12, 24, 48, 96} investments.
Measures:
1. Probability of at least one outlier returning >= 20x.
2. Profit concentration: fraction of total fund proceeds generated by the single best investment.
3. Fund TVPI dispersion: Mean TVPI, Median TVPI, and Probability of losing capital (TVPI < 1.0).

Standard library and NumPy only; fully deterministic with fixed seed.
"""

from __future__ import annotations

import numpy as np


def generate_deal_returns(n_deals: int, rng: np.random.Generator) -> np.ndarray:
    """Generate deal return multiples from the venture mixture distribution."""
    u = rng.uniform(0.0, 1.0, n_deals)
    returns = np.zeros(n_deals, dtype=np.float64)

    # 60% failure
    mask_fail = u < 0.60
    returns[mask_fail] = rng.uniform(0.0, 0.8, int(np.sum(mask_fail)))

    # 30% modest success
    mask_mod = (u >= 0.60) & (u < 0.90)
    returns[mask_mod] = rng.uniform(1.0, 5.0, int(np.sum(mask_mod)))

    # 10% power-law tail: Pareto(x_m=5.0, alpha=1.4)
    mask_tail = u >= 0.90
    n_tail = int(np.sum(mask_tail))
    if n_tail > 0:
        u_tail = rng.uniform(0.0001, 1.0, n_tail)
        returns[mask_tail] = 5.0 / (u_tail ** (1.0 / 1.4))

    return returns


def main() -> None:
    rng = np.random.default_rng(42)
    n_sims = 5_000
    portfolio_sizes = [12, 24, 48, 96]

    print("--- Venture Portfolio Outcomes by Fund Size ---")
    for n in portfolio_sizes:
        tvpis = np.zeros(n_sims, dtype=np.float64)
        has_20x = np.zeros(n_sims, dtype=bool)
        top_share = np.zeros(n_sims, dtype=np.float64)

        for s in range(n_sims):
            deals = generate_deal_returns(n, rng)
            tvpi = float(np.mean(deals))
            tvpis[s] = tvpi
            has_20x[s] = bool(np.any(deals >= 20.0))
            top_share[s] = float(np.max(deals) / np.sum(deals))

        prob_20x = float(np.mean(has_20x)) * 100.0
        mean_tvpi = float(np.mean(tvpis))
        median_tvpi = float(np.median(tvpis))
        prob_loss = float(np.mean(tvpis < 1.0)) * 100.0
        avg_top_share = float(np.mean(top_share)) * 100.0

        print(
            f"N={n:2d}: P(Deal >= 20x)={prob_20x:4.1f}% | "
            f"Mean TVPI={mean_tvpi:.2f}x | Median TVPI={median_tvpi:.2f}x | "
            f"P(TVPI < 1.0)={prob_loss:4.1f}% | Top Deal Share={avg_top_share:4.1f}%"
        )


main()
