"""Lab BK1-L03-1: Net interest margin (NIM) and interest rate resets.

Net interest margin (NIM) measures the net yield generated by a bank's earning assets:
    NIM = (Interest Income - Interest Expense) / Average Earning Assets = NII / AEA

When interest rates change, NIM responds according to the relative repricing speeds
of assets versus liabilities. If liabilities reprice faster than assets (liability-sensitive),
rising interest rates squeeze the net interest margin.

This lab simulates:
1. Base balance sheet (SIMULATED, in cents):
   - Average Earning Assets (AEA): 100,000,000 cents ($1,000,000) earning 5.50% (550 bp)
   - Interest-Bearing Liabilities (IBL): 80,000,000 cents ($800,000) paying 2.50% (250 bp)
   - Equity: 20,000,000 cents ($200,000)
2. Asymmetric repricing speeds:
   - Asset repricing share: 40% (60% fixed)
   - Liability repricing share: 70% (30% fixed)
3. Rate shock scenarios: +100 bp, +200 bp, -100 bp.
"""

from __future__ import annotations

from fractions import Fraction

AEA_CENTS = 100_000_000  # $1,000,000 average earning assets
IBL_CENTS = 80_000_000  # $800,000 interest-bearing liabilities
BASE_ASSET_YIELD_BP = 550  # 5.50%
BASE_LIAB_COST_BP = 250  # 2.50%

ASSET_REPRICING_SHARE = Fraction(40, 100)  # 40%
LIAB_REPRICING_SHARE = Fraction(70, 100)  # 70%


def compute_nim(shock_bp: int) -> dict[str, int]:
    """Calculate annual interest income, expense, NII, and NIM in basis points."""
    # New effective rates in bp as Fractions
    effective_asset_bp = Fraction(BASE_ASSET_YIELD_BP, 1) + ASSET_REPRICING_SHARE * Fraction(shock_bp, 1)
    effective_liab_bp = Fraction(BASE_LIAB_COST_BP, 1) + LIAB_REPRICING_SHARE * Fraction(shock_bp, 1)

    income = Fraction(AEA_CENTS, 1) * (effective_asset_bp / Fraction(10_000, 1))
    expense = Fraction(IBL_CENTS, 1) * (effective_liab_bp / Fraction(10_000, 1))
    nii = income - expense
    nim_bp = (nii / Fraction(AEA_CENTS, 1)) * Fraction(10_000, 1)

    return {
        "shock_bp": shock_bp,
        "income_cents": int(income),
        "expense_cents": int(expense),
        "nii_cents": int(nii),
        "nim_bp": int(nim_bp),
    }


def main() -> None:
    print("A. Net Interest Margin under Asymmetric Repricing (SIMULATED, in cents)")
    base = compute_nim(0)
    print(
        f"Base (0 bp)  | Income: {base['income_cents']:8d} | Expense: {base['expense_cents']:8d} | "
        f"NII: {base['nii_cents']:8d} | NIM: {base['nim_bp']:4d} bp"
    )

    shocks = [100, 200, -100]
    for s in shocks:
        res = compute_nim(s)
        delta_nii = res["nii_cents"] - base["nii_cents"]
        delta_nim = res["nim_bp"] - base["nim_bp"]
        print(
            f"Shock {s:+4d} bp | Income: {res['income_cents']:8d} | Expense: {res['expense_cents']:8d} | "
            f"NII: {res['nii_cents']:8d} ({delta_nii:+7d}) | NIM: {res['nim_bp']:4d} bp ({delta_nim:+3d} bp)"
        )

    print()
    print("B. NIM Sensitivity Invariant Checks")
    # Verify exact NIM formula: NIM = y_A - y_L * (IBL / AEA)
    # At base: 550 - 250 * (80/100) = 550 - 200 = 350 bp
    expected_base_nim = BASE_ASSET_YIELD_BP - int(BASE_LIAB_COST_BP * Fraction(IBL_CENTS, AEA_CENTS))
    print(f"Base NIM equals theoretical formula (350 bp): {base['nim_bp'] == expected_base_nim}")

    # For liability-sensitive bank (IBL repricing share > AEA repricing share),
    # positive rate shock compresses NIM:
    res_pos = compute_nim(100)
    print(f"Positive rate shock compresses NIM for liability-sensitive book: {res_pos['nim_bp'] < base['nim_bp']}")


main()
