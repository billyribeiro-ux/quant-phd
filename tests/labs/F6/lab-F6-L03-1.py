"""Lab F6-L03-1: Instrumented PCA via Alternating Least Squares.

Implements Kelly, Pruitt & Su (2019) Instrumented Principal Component Analysis (IPCA).
Instruments latent factor loadings with dynamic firm characteristics:
r_{i,t+1} = z_{i,t}^T Gamma_beta f_{t+1} + eps_{i,t+1}
and estimates latent factors and loading mapping via Alternating Least Squares (ALS).
"""

from __future__ import annotations

import numpy as np


def run_lab(seed: int = 42) -> dict[str, float]:
    """Execute IPCA Alternating Least Squares estimation on characteristic panel."""
    rng = np.random.default_rng(seed)

    n_assets = 25
    n_periods = 40
    n_chars = 4
    n_factors = 2

    # Simulated panel of firm characteristics in [-0.5, 0.5]
    z_panel = rng.uniform(-0.5, 0.5, size=(n_periods, n_assets, n_chars))

    # True Gamma_beta matrix mapping characteristics to dynamic loadings
    gamma_true = np.array(
        [[1.0, 0.0], [0.5, 0.5], [0.0, 1.0], [-0.5, 0.2]],
        dtype=np.float64,
    )
    # Latent systematic factors
    f_true = rng.normal(0.010, 0.045, size=(n_periods, n_factors))

    # Realized returns generated by instrumented risk exposures plus noise
    returns = np.zeros((n_periods, n_assets), dtype=np.float64)
    for t in range(n_periods):
        betas_t = z_panel[t] @ gamma_true  # (N, K)
        returns[t] = betas_t @ f_true[t] + rng.normal(0.0, 0.050, size=n_assets)

    # Alternating Least Squares (ALS) Estimation
    gamma_est = np.eye(n_chars, n_factors, dtype=np.float64)
    max_iters = 20
    tol = 1e-6
    final_iter = 0

    for it in range(max_iters):
        gamma_prev = gamma_est.copy()

        # Step 1: Given Gamma_beta, estimate latent factor realizations f_t for each period
        factors = np.zeros((n_periods, n_factors), dtype=np.float64)
        for t in range(n_periods):
            betas_t = z_panel[t] @ gamma_est
            factors[t] = np.linalg.solve(
                betas_t.T @ betas_t + 1e-5 * np.eye(n_factors),
                betas_t.T @ returns[t],
            )

        # Step 2: Given factors f_t, estimate Gamma_beta across all pooled observations
        lhs = np.zeros((n_chars * n_factors, n_chars * n_factors), dtype=np.float64)
        rhs = np.zeros(n_chars * n_factors, dtype=np.float64)
        for t in range(n_periods):
            zt_zt = z_panel[t].T @ z_panel[t]
            ft_ft = np.outer(factors[t], factors[t])
            lhs += np.kron(ft_ft, zt_zt)
            rhs += np.kron(factors[t], z_panel[t].T @ returns[t])

        vec_gamma = np.linalg.solve(lhs + 1e-5 * np.eye(n_chars * n_factors), rhs)
        gamma_raw = vec_gamma.reshape(n_factors, n_chars).T

        # QR orthonormalization to identify factor rotation
        q_mat, _ = np.linalg.qr(gamma_raw)
        gamma_est = q_mat

        diff = float(np.linalg.norm(gamma_est - gamma_prev))
        final_iter = it + 1
        if diff < tol:
            break

    # Compute Total R2 and Predictive R2
    fitted_returns = np.zeros_like(returns)
    pred_returns = np.zeros_like(returns)
    f_mean = np.mean(factors, axis=0)

    for t in range(n_periods):
        betas_t = z_panel[t] @ gamma_est
        fitted_returns[t] = betas_t @ factors[t]
        pred_returns[t] = betas_t @ f_mean

    ss_tot = float(np.sum(returns**2))
    r2_total = float(1.0 - np.sum((returns - fitted_returns) ** 2) / ss_tot)
    r2_pred = float(1.0 - np.sum((returns - pred_returns) ** 2) / ss_tot)

    return {
        "final_iter": float(final_iter),
        "r2_total_pct": r2_total * 100.0,
        "r2_pred_pct": r2_pred * 100.0,
        "f1_vol_pct": float(np.std(factors[:, 0], ddof=1) * np.sqrt(12.0) * 100.0),
    }


def main() -> None:
    res = run_lab(seed=42)
    print("=== Lab F6-L03-1: Instrumented PCA (Kelly, Pruitt & Su 2019) ===")
    print(f"ALS Converged in Iterations: {int(res['final_iter'])}")
    print(f"IPCA Total R2 (%):          {res['r2_total_pct']:.4f}")
    print(f"IPCA Predictive R2 (%):     {res['r2_pred_pct']:.4f}")
    print(f"Factor 1 Annual Volatility (%): {res['f1_vol_pct']:.4f}")


main()
