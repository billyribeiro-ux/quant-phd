"""M7 lab L02: minimum-variance weights under a budget constraint, solved in exact arithmetic.

Standard library only. No randomness and no network. The inputs come from a fixed linear congruential generator,
so every run reads the same numbers. Every computation uses fractions.Fraction, so the residuals are exact zeros
or exact non-zero values, not rounding errors.

SIMULATED: the symmetric positive definite matrix Sigma is generated by this lab from a fixed seed.
It is an illustrative input, not an estimate from data. The lab does not estimate Sigma and does not
claim that it describes any market.

The problem is: minimize f(w) = (1/2) w' Sigma w over w in R^3, subject to 1' w = 1. The lab
1. forms Sigma = A' A + I from a 3 x 3 integer matrix A (so Sigma is symmetric and positive definite);
2. solves Sigma u = 1 by exact Gaussian elimination, sets lambda = 1 / (1' u) and w = lambda u;
3. checks that the budget holds exactly, that the gradient Sigma w equals lambda times the constraint normal 1
   exactly, and that f(w + t d) - f(w) equals (1/2) t^2 d' Sigma d for six directions d with 1' d = 0 and six
   values of t, so the increase is non-negative in every tested case.

Checks on six directions and six step sizes are checks on those cases only. The claim for all directions is the
proof on the page: Proposition 3.2 of the lesson gives the minimizer under the assumption that Sigma is positive
definite, and Proposition 3.3 shows that A' A + I is positive definite for every real square A.
"""

from __future__ import annotations

from fractions import Fraction

SEED = 1
SIZE = 3


def lcg_integers(seed: int, count: int) -> list[int]:
    """Deterministic integers in -3 to 3 from a linear congruential generator with fixed constants."""
    state = seed
    values: list[int] = []
    for _ in range(count):
        state = (1103515245 * state + 12345) % 2**31
        values.append(state % 7 - 3)
    return values


def gram_plus_identity(entries: list[int], size: int) -> list[list[Fraction]]:
    """Sigma = A' A + I for the size x size matrix A given row by row in entries."""
    a = [[entries[i * size + j] for j in range(size)] for i in range(size)]
    sigma: list[list[Fraction]] = []
    for i in range(size):
        row: list[Fraction] = []
        for j in range(size):
            value = sum(a[k][i] * a[k][j] for k in range(size)) + (1 if i == j else 0)
            row.append(Fraction(value))
        sigma.append(row)
    return sigma


def solve(matrix: list[list[Fraction]], rhs: list[Fraction]) -> list[Fraction]:
    """Solve matrix x = rhs by Gaussian elimination with exact fractions and partial pivoting."""
    n = len(rhs)
    rows = [[*matrix[i], rhs[i]] for i in range(n)]
    for col in range(n):
        pivot = next((r for r in range(col, n) if rows[r][col] != 0), None)
        if pivot is None:
            raise ValueError("the matrix is singular, so the system has no unique solution")
        rows[col], rows[pivot] = rows[pivot], rows[col]
        for r in range(n):
            if r != col and rows[r][col] != 0:
                factor = rows[r][col] / rows[col][col]
                rows[r] = [a - factor * b for a, b in zip(rows[r], rows[col], strict=True)]
    return [rows[i][n] / rows[i][i] for i in range(n)]


def matvec(matrix: list[list[Fraction]], x: list[Fraction]) -> list[Fraction]:
    """The product matrix times x, exact."""
    return [sum((a * b for a, b in zip(row, x, strict=True)), Fraction(0)) for row in matrix]


def quadratic(sigma: list[list[Fraction]], x: list[Fraction]) -> Fraction:
    """The value x' Sigma x, exact."""
    return sum((a * b for a, b in zip(x, matvec(sigma, x), strict=True)), Fraction(0))


def directions() -> list[list[Fraction]]:
    """Six directions d with 1' d = 0 (components sum to zero), exact."""
    raw = [(1, -1, 0), (0, 1, -1), (1, 0, -1), (2, -1, -1), (-1, 2, -1), (1, 1, -2)]
    return [[Fraction(c) for c in d] for d in raw]


def main() -> None:
    entries = lcg_integers(SEED, SIZE * SIZE)
    print(f"A entries (row by row, seed {SEED}): {entries}")
    sigma = gram_plus_identity(entries, SIZE)
    print("Sigma = A' A + I:")
    for row in sigma:
        print("  " + " ".join(str(x) for x in row))

    ones = [Fraction(1)] * SIZE
    u = solve(sigma, ones)
    total = sum(u, Fraction(0))
    lam = 1 / total
    w = [lam * x for x in u]
    print(f"1' Sigma^-1 1 = {total}, multiplier lambda = {lam}")
    print("minimum-variance weights w = lambda Sigma^-1 1:")
    print("  " + " ".join(str(x) for x in w))

    budget = sum(w, Fraction(0))
    print(f"budget 1' w = {budget}, equal to 1 exactly: {budget == 1}")
    gradient = matvec(sigma, w)
    residual = [g - lam * one for g, one in zip(gradient, ones, strict=True)]
    exact_zero = all(r == 0 for r in residual)
    print(f"gradient Sigma w minus lambda 1: {[str(r) for r in residual]}, all exactly zero: {exact_zero}")

    fw = quadratic(sigma, w) / 2
    print(f"objective f(w) = (1/2) w' Sigma w = {fw}")
    steps = [Fraction(-1, 2), Fraction(1, 2), Fraction(1), Fraction(-1), Fraction(2), Fraction(3, 2)]
    identity_ok = 0
    increases_ok = 0
    tested = 0
    for d in directions():
        dsd = quadratic(sigma, d)
        for t in steps:
            moved = [wi + t * di for wi, di in zip(w, d, strict=True)]
            gap = quadratic(sigma, moved) / 2 - fw
            tested += 1
            identity_ok += gap == t * t * dsd / 2
            increases_ok += gap >= 0
    print(f"f(w + t d) - f(w) equals (1/2) t^2 d' Sigma d in {identity_ok} of {tested} tested cases")
    print(f"f(w + t d) - f(w) is non-negative in {increases_ok} of {tested} tested cases")


main()
