"""LX2 project lab 3 (rung 3 check): the outcomes table of the case model, on a seeded SIMULATED case.

SIMULATED. The realised values are generated by a seeded pseudo-random generator, random.Random(SEED) with
SEED = 20261103, and are not data. The generator draws one integer noise term for each month index t from 1 to 36,
in order, uniform on -3 to 3 inclusive (random.Random.randint). The realised value of month t is
100 + 2 * t + noise, and 6 units less from month 28 on. The seed and the generator are the case inputs: running this
file reproduces them exactly.

The case model is the model of rung 1: forecast(t) = 100 + 2 * t units (assumption M1). Its forecast for month t
uses no information from month t (assumption M2). The calibration window is months 1 to 12 and the validation window
is months 13 to 36, so H = 24 months. Only the validation window enters the outcomes measures.

Error and hit. The error of month t is e = forecast - realised, in units. A month is a hit when |e| <= 2 (a band of
2 units, inclusive, as in Lesson 4 of this unit).

Hit rate. The hit rate is the number of hits divided by H.

Bias. The bias is (1 / H) times the sum of e over the validation window, in units per month. A positive bias means
the model forecasts too high on average.

Part A: the validation table, one line per month: forecast, realised value, error and hit.
Part B: the number of hits and the hit rate, to four decimals.
Part C: the bias over the validation window, in units per month, to four decimals.
Part D: the months with |error| = 2 exactly, which are hits at the edge of the band.
Part E: the month with the largest absolute error, the earliest such month on a tie.
Part F: the bias over the calibration window, in units per month, to four decimals. It checks the calibration fit. It is
not part of the outcomes measures.

The hit rate and both biases are exact Fractions. A value is rounded once, when it is printed: half up (a tie goes away
from zero).
"""

from __future__ import annotations

import math
import random
from fractions import Fraction

SEED = 20261103
LAST_MONTH = 36
CALIBRATION_END = 12
HIT_BAND = 2
SHIFT_FROM = 28
SHIFT_UNITS = -6


def forecast(t: int) -> int:
    """The case model's forecast for month index t, in units: 100 + 2 * t (assumption M1)."""
    return 100 + 2 * t


def is_hit(predicted: int, realised: int) -> bool:
    """True when the absolute error is at most the band of 2 units: |forecast - realised| <= 2."""
    if realised <= 0:
        raise ValueError(f"the realised value must be a positive count of units, got {realised}")
    return abs(predicted - realised) <= HIT_BAND


def simulate_realised(seed: int) -> dict[int, int]:
    """The realised values of months 1 to 36, in units: 100 + 2 * t + noise, less 6 units from month 28 on."""
    rng = random.Random(seed)
    realised: dict[int, int] = {}
    for t in range(1, LAST_MONTH + 1):
        noise = rng.randint(-3, 3)
        shift = SHIFT_UNITS if t >= SHIFT_FROM else 0
        realised[t] = 100 + 2 * t + noise + shift
    return realised


def decimal_text(value: Fraction, places: int) -> str:
    """The value rounded half up (a tie goes away from zero) to places decimals, with exactly places digits."""
    scale = 10**places
    magnitude = math.floor(abs(value) * scale + Fraction(1, 2))
    sign = "-" if value < 0 and magnitude != 0 else ""
    whole, part = divmod(magnitude, scale)
    if places == 0:
        return f"{sign}{whole}"
    return f"{sign}{whole}.{part:0{places}d}"


def main() -> None:
    realised = simulate_realised(SEED)
    print(f"SIMULATED case, seed {SEED}: forecast(t) = 100 + 2t units; validation months 13 to 36, H = 24; band 2")
    print("Part A: month, forecast, realised, error (forecast - realised), hit")
    errors: dict[int, int] = {}
    hits = 0
    for t in range(CALIBRATION_END + 1, LAST_MONTH + 1):
        predicted = forecast(t)
        error = predicted - realised[t]
        errors[t] = error
        hit = is_hit(predicted, realised[t])
        if hit:
            hits += 1
        print(f"  t={t} forecast={predicted} realised={realised[t]} error={error:+d} hit={'yes' if hit else 'no'}")
    horizon = len(errors)
    hit_rate = Fraction(hits, horizon)
    print(f"Part B: hits {hits} of {horizon}; hit rate {decimal_text(hit_rate, 4)}")
    bias = Fraction(sum(errors.values()), horizon)
    print(f"Part C: bias {decimal_text(bias, 4)} units per month")
    edge = [t for t, e in errors.items() if abs(e) == HIT_BAND]
    print(f"Part D: months with |error| = 2 exactly (hits at the edge): {edge}")
    worst = max(errors, key=lambda t: (abs(errors[t]), -t))
    print(f"Part E: largest absolute error {abs(errors[worst])} units, month {worst}")
    calibration = [forecast(t) - realised[t] for t in range(1, CALIBRATION_END + 1)]
    calibration_bias = Fraction(sum(calibration), len(calibration))
    print(f"Part F: calibration-window bias {decimal_text(calibration_bias, 4)} units per month (months 1 to 12)")


main()
