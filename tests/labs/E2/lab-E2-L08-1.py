"""E2 L08 lab 1 (SIMULATED): the winner's curse in a common-value auction, and a shading rule that offsets it.

SIMULATED. Every value and signal below is generated by a seeded pseudo-random generator. No auction data is used.

Model, in integer cents. The common value V is uniform on the whole numbers 5000 to 15000. Bidder i observes
the signal S_i = V + E_i, where the noises E_i are independent and uniform on the whole numbers -2000 to 2000.
There are n = 5 bidders and one unit. The highest bidder wins and pays its own bid, and ties go to the lower
bidder index. Each winner's profit in cents is V minus the price it pays.

Part A checks the exact formula for the expected largest noise M = max(E_1, ..., E_n) against a full enumeration
of the nine noise pairs for n = 2 and a half-width of 1 cent.
Part B bids the signal itself (the naive rule) in 20000 simulated auctions with seed 20261028, and prints the
total profit of the winner, next to the exact expected total.
Part C bids the signal less a shading amount c, equal to the rounded exact expected largest noise, in the same
simulated auctions, and prints the total profit of the winner, next to the exact expected total.

Totals are whole cents. The exact expected totals are rounded to the nearest whole cent, a tie going up. Each
simulated total is printed with its standard error, the estimated sampling error of a total over the auctions.
"""

from __future__ import annotations

import itertools
import math
import random
from fractions import Fraction

HALF_WIDTH = 2000
BIDDERS = 5
AUCTIONS = 20000
SEED = 20261028
V_LOW = 5000
V_HIGH = 15000


def expected_max_noise(n: int, a: int) -> Fraction:
    """Exact E[M] for M the largest of n independent noises, each uniform on the whole numbers -a to a.

    P(M <= x) = ((x + a + 1) / (2a + 1))^n for whole x in -a..a, and M + a = sum over x in -a..a-1 of 1{M > x}.
    """
    total = Fraction(-a)
    for x in range(-a, a):
        cdf = Fraction(x + a + 1, 2 * a + 1) ** n
        total += 1 - cdf
    return total


def enumerated_expected_max_noise(n: int, a: int) -> Fraction:
    """Exact E[M] by listing every tuple of noises; feasible only for small n and a."""
    values = range(-a, a + 1)
    tuples = list(itertools.product(values, repeat=n))
    return Fraction(sum(max(t) for t in tuples), len(tuples))


def half_up_cents(amount: Fraction) -> int:
    """The amount in whole cents, a tie going up."""
    return math.floor(amount + Fraction(1, 2))


def run_auctions(shade: int, rng: random.Random) -> list[int]:
    """Profit in cents of the winner in each of AUCTIONS auctions, when each bidder bids its signal less shade."""
    profits: list[int] = []
    for _ in range(AUCTIONS):
        value = rng.randint(V_LOW, V_HIGH)
        signals = [value + rng.randint(-HALF_WIDTH, HALF_WIDTH) for _ in range(BIDDERS)]
        bids = [s - shade for s in signals]
        winner = max(range(BIDDERS), key=lambda i: (bids[i], -i))
        profits.append(value - bids[winner])
    return profits


def standard_error_of_total(profits: list[int]) -> int:
    """Standard error of the simulated total profit, in whole cents, a tie going up.

    The sample variance of the profits is (N * sum of squares - (sum)^2) / (N * (N - 1)), so the standard error
    of the total over N auctions is the square root of N times that variance, which is the square root of
    (N * sum of squares - (sum)^2) / (N - 1).
    """
    n = len(profits)
    numerator = n * sum(p * p for p in profits) - sum(profits) ** 2
    return math.floor(math.sqrt(numerator / (n - 1)) + 0.5)


def main() -> None:
    """Print Parts A, B and C in order. The output is fixed by the seed."""
    print("Part A: expected largest noise, formula against enumeration")
    formula = expected_max_noise(2, 1)
    enumerated = enumerated_expected_max_noise(2, 1)
    print(f"pairs_enumerated {len(list(itertools.product(range(-1, 2), repeat=2)))}")
    print(f"formula_n2_a1 {formula}")
    print(f"enumeration_n2_a1 {enumerated}")
    print(f"formula_equals_enumeration {formula == enumerated}")

    expected = expected_max_noise(BIDDERS, HALF_WIDTH)
    shade = half_up_cents(expected)
    print(f"Part B: naive bids equal the signal, n = {BIDDERS}, half-width {HALF_WIDTH} cents, {AUCTIONS} auctions")
    naive = run_auctions(0, random.Random(SEED))
    print(f"naive_winner_profit_total_cents {sum(naive)}")
    print(f"naive_standard_error_cents {standard_error_of_total(naive)}")
    print(f"exact_naive_winner_profit_total_cents {half_up_cents(-AUCTIONS * expected)}")

    print(f"Part C: shaded bids, shade {shade} cents, the rounded exact expected largest noise")
    shaded = run_auctions(shade, random.Random(SEED))
    print(f"shade_cents {shade}")
    print(f"shaded_winner_profit_total_cents {sum(shaded)}")
    print(f"shaded_standard_error_cents {standard_error_of_total(shaded)}")
    print(f"exact_shaded_winner_profit_total_cents {half_up_cents(AUCTIONS * (shade - expected))}")


main()
